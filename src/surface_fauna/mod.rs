//! Roaming fauna on the planet surface and inside the maze venues.
//!
//! Roamers (deer, rabbit, fox, …) wander tile-to-tile within their home
//! terrains, pause to graze, and bolt when the player comes near — the mobile
//! evolution of the static `shy` peekers in `surface_objects`.  Fliers
//! (songbird, butterfly, drones) cruise over the map ignoring terrain and drop
//! a shadow on the ground below them.
//!
//! Everything shares the [`CharacterAnim`](crate::surface_character::CharacterAnim)
//! directional walk animation, driven by `LinearVelocity`, so these modules own
//! only the AI and the depth sorting:
//!
//! * [`spawn`] — keep a small off-screen-recycling population alive.
//! * [`behaviour`] — the graze / wander / flee / alert state machine.
//! * [`render`] — depth sorting and flier shadows.
//!
//! Art + per-species data come from `assets/sprites/fauna/fauna_manifest.ron`
//! (generated by `scripts/ship3d/fauna3d.py`).

